-- PawCare v1: single-store pet bathing and grooming.
-- PostgreSQL foundation DDL, NOT a finished business-rule implementation.
-- Run once in a database where schema pawcare does not already exist.
-- No existing schemas or data are dropped. All currency amounts are AUD.
-- Cross-row rules (ownership, conflicts, stock, refunds, workflow transitions)
-- require the transactions described in the design document. CHECK constraints
-- here deliberately do not claim to enforce those cross-row rules.

BEGIN;
CREATE SCHEMA pawcare;
SET LOCAL search_path TO pawcare, public;

CREATE TABLE user_account (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (email = lower(btrim(email)) AND length(email) > 0),
    CHECK (length(password_hash) > 0)
);

CREATE TABLE customer (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name varchar(100) NOT NULL CHECK (length(btrim(display_name)) > 0),
    phone varchar(32) NOT NULL CHECK (length(btrim(phone)) > 0),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active boolean NOT NULL DEFAULT true
);

-- An absent binding is an absent relationship row, not a nullable candidate key.
CREATE TABLE customer_account (
    customer_id bigint PRIMARY KEY REFERENCES customer(customer_id),
    account_id bigint NOT NULL UNIQUE REFERENCES user_account(account_id)
);

CREATE TABLE pet (
    pet_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customer(customer_id),
    pet_name varchar(80) NOT NULL CHECK (length(btrim(pet_name)) > 0),
    species varchar(8) NOT NULL CHECK (species IN ('dog', 'cat')),
    breed varchar(100),
    birth_date date,
    sex varchar(8) NOT NULL DEFAULT 'unknown' CHECK (sex IN ('female', 'male', 'unknown')),
    latest_weight_kg numeric(6,2) CHECK (latest_weight_kg > 0),
    care_notes text,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE employee (
    employee_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL UNIQUE REFERENCES user_account(account_id),
    employee_code varchar(30) NOT NULL UNIQUE,
    display_name varchar(100) NOT NULL,
    staff_role varchar(20) NOT NULL CHECK (staff_role IN ('manager', 'receptionist', 'groomer')),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE service (
    service_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_code varchar(30) NOT NULL UNIQUE,
    service_name varchar(100) NOT NULL,
    species varchar(8) NOT NULL CHECK (species IN ('dog', 'cat')),
    workstation_type varchar(10) NOT NULL CHECK (workstation_type IN ('wash', 'groom')),
    base_price numeric(10,2) NOT NULL CHECK (base_price >= 0),
    default_duration_minutes integer NOT NULL CHECK (default_duration_minutes > 0),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE employee_service (
    employee_id bigint NOT NULL REFERENCES employee(employee_id),
    service_id bigint NOT NULL REFERENCES service(service_id),
    is_active boolean NOT NULL DEFAULT true,
    authorised_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (employee_id, service_id)
);

CREATE TABLE workstation (
    workstation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_code varchar(30) NOT NULL UNIQUE,
    station_name varchar(100) NOT NULL,
    workstation_type varchar(10) NOT NULL CHECK (workstation_type IN ('wash', 'groom')),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE employee_shift (
    shift_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES employee(employee_id),
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    UNIQUE (employee_id, starts_at),
    UNIQUE (employee_id, ends_at),
    CHECK (ends_at > starts_at)
);

CREATE TABLE appointment (
    appointment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code varchar(30) NOT NULL UNIQUE,
    customer_id bigint NOT NULL REFERENCES customer(customer_id),
    created_by_account_id bigint NOT NULL REFERENCES user_account(account_id),
    requested_start_at timestamptz NOT NULL,
    customer_note text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    -- Overall status and totals are derived, not stored here.
);

CREATE TABLE appointment_item (
    appointment_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id bigint NOT NULL REFERENCES appointment(appointment_id),
    item_no integer NOT NULL CHECK (item_no > 0),
    pet_id bigint NOT NULL REFERENCES pet(pet_id),
    service_id bigint NOT NULL REFERENCES service(service_id),
    employee_id bigint,
    workstation_id bigint REFERENCES workstation(workstation_id),
    planned_start_at timestamptz,
    planned_end_at timestamptz,
    agreed_price numeric(10,2) CHECK (agreed_price >= 0),
    state varchar(20) NOT NULL DEFAULT 'requested'
        CHECK (state IN ('requested','scheduled','in_progress','completed','cancelled','no_show')),
    UNIQUE (appointment_id, item_no),
    FOREIGN KEY (employee_id, service_id) REFERENCES employee_service(employee_id, service_id),
    CHECK (
        (employee_id IS NULL AND workstation_id IS NULL AND planned_start_at IS NULL AND planned_end_at IS NULL)
        OR
        (employee_id IS NOT NULL AND workstation_id IS NOT NULL AND planned_start_at IS NOT NULL AND planned_end_at IS NOT NULL)
    ),
    CHECK (state IN ('requested', 'cancelled') OR (employee_id IS NOT NULL AND agreed_price IS NOT NULL)),
    CHECK (planned_end_at > planned_start_at)
    -- Planned duration is derived from the two timestamps, never stored twice.
);

CREATE TABLE service_record (
    appointment_item_id bigint PRIMARY KEY REFERENCES appointment_item(appointment_item_id),
    actual_start_at timestamptz NOT NULL,
    actual_end_at timestamptz,
    weight_at_visit_kg numeric(6,2) CHECK (weight_at_visit_kg > 0),
    care_notes text,
    result_notes text,
    CHECK (actual_end_at >= actual_start_at)
    -- A record starts when the item becomes in_progress; it is closed on completion.
);

CREATE TABLE consumable (
    consumable_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(40) NOT NULL UNIQUE,
    consumable_name varchar(100) NOT NULL,
    base_unit varchar(10) NOT NULL CHECK (base_unit IN ('ml', 'g', 'unit')),
    reorder_level numeric(12,3) NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    is_active boolean NOT NULL DEFAULT true
    -- Current quantity is the SUM of inventory_movement.quantity_delta.
);

CREATE TABLE service_consumable (
    service_id bigint NOT NULL REFERENCES service(service_id),
    consumable_id bigint NOT NULL REFERENCES consumable(consumable_id),
    expected_quantity numeric(12,3) NOT NULL CHECK (expected_quantity > 0),
    PRIMARY KEY (service_id, consumable_id)
);

CREATE TABLE inventory_movement (
    movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumable_id bigint NOT NULL REFERENCES consumable(consumable_id),
    movement_kind varchar(12) NOT NULL CHECK (movement_kind IN ('receipt', 'use', 'waste', 'adjustment')),
    quantity_delta numeric(12,3) NOT NULL CHECK (quantity_delta <> 0),
    recorded_by_employee_id bigint NOT NULL REFERENCES employee(employee_id),
    reason text NOT NULL CHECK (length(btrim(reason)) > 0),
    request_key varchar(80) NOT NULL UNIQUE,
    recorded_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (movement_kind = 'receipt' AND quantity_delta > 0)
        OR (movement_kind IN ('use','waste') AND quantity_delta < 0)
        OR movement_kind = 'adjustment'
    )
);

-- Optional source association kept separate from the movement facts.
-- This avoids treating a nullable source as a global candidate key, or storing
-- a service source beside a movement kind it conditionally determines.
CREATE TABLE service_consumption (
    movement_id bigint PRIMARY KEY REFERENCES inventory_movement(movement_id),
    service_record_id bigint NOT NULL REFERENCES service_record(appointment_item_id)
    -- The completion transaction must ensure the parent kind is 'use', link every
    -- service-use movement exactly once, and consolidate each item's consumable.
);

CREATE TABLE payment (
    payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id bigint NOT NULL REFERENCES appointment(appointment_id),
    receipt_code varchar(40) NOT NULL UNIQUE,
    amount numeric(10,2) NOT NULL CHECK (amount > 0),
    method varchar(12) NOT NULL CHECK (method IN ('cash','card','transfer')),
    received_by_employee_id bigint NOT NULL REFERENCES employee(employee_id),
    request_key varchar(80) NOT NULL UNIQUE,
    received_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    -- Only actual received money is recorded; there is no gateway integration.
);

CREATE TABLE refund (
    refund_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id bigint NOT NULL REFERENCES payment(payment_id),
    refund_code varchar(40) NOT NULL UNIQUE,
    amount numeric(10,2) NOT NULL CHECK (amount > 0),
    reason text NOT NULL CHECK (length(btrim(reason)) > 0),
    processed_by_employee_id bigint NOT NULL REFERENCES employee(employee_id),
    request_key varchar(80) NOT NULL UNIQUE,
    refunded_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    -- Check original unrefunded amount AND appointment refund_due under locks.
);

CREATE INDEX pet_customer_idx ON pet(customer_id);
CREATE INDEX employee_service_service_idx ON employee_service(service_id);
CREATE INDEX shift_employee_time_idx ON employee_shift(employee_id, starts_at, ends_at);
CREATE INDEX appointment_customer_time_idx ON appointment(customer_id, requested_start_at);
CREATE INDEX item_employee_time_idx ON appointment_item(employee_id, planned_start_at, planned_end_at);
CREATE INDEX item_station_time_idx ON appointment_item(workstation_id, planned_start_at, planned_end_at);
CREATE INDEX item_pet_time_idx ON appointment_item(pet_id, planned_start_at, planned_end_at);
CREATE INDEX movement_consumable_time_idx ON inventory_movement(consumable_id, recorded_at);
CREATE INDEX consumption_record_idx ON service_consumption(service_record_id);
CREATE INDEX payment_appointment_idx ON payment(appointment_id);
CREATE INDEX refund_payment_idx ON refund(payment_id);

CREATE VIEW inventory_balance AS
SELECT c.consumable_id, c.sku, c.consumable_name, c.base_unit, c.reorder_level,
       COALESCE(SUM(m.quantity_delta), 0)::numeric(14,3) AS quantity_on_hand
FROM consumable c
LEFT JOIN inventory_movement m USING (consumable_id)
GROUP BY c.consumable_id;

-- Aggregate each one-to-many relation separately to avoid double counting.
CREATE VIEW appointment_financials AS
WITH charges AS (
    SELECT appointment_id,
           SUM(agreed_price) FILTER (WHERE state IN ('scheduled','in_progress','completed')) AS charge_total
    FROM appointment_item GROUP BY appointment_id
), receipts AS (
    SELECT appointment_id, SUM(amount) AS paid_total FROM payment GROUP BY appointment_id
), refunds AS (
    SELECT p.appointment_id, SUM(r.amount) AS refunded_total
    FROM payment p JOIN refund r USING (payment_id) GROUP BY p.appointment_id
), amounts AS (
    SELECT a.appointment_id, a.booking_code,
           COALESCE(c.charge_total, 0)::numeric(14,2) AS charge_total,
           COALESCE(p.paid_total, 0)::numeric(14,2) AS paid_total,
           COALESCE(r.refunded_total, 0)::numeric(14,2) AS refunded_total
    FROM appointment a
    LEFT JOIN charges c USING (appointment_id)
    LEFT JOIN receipts p USING (appointment_id)
    LEFT JOIN refunds r USING (appointment_id)
)
SELECT *, paid_total - refunded_total AS net_paid,
       GREATEST(charge_total - paid_total + refunded_total, 0) AS amount_due,
       GREATEST(paid_total - refunded_total - charge_total, 0) AS refund_due
FROM amounts;

CREATE VIEW appointment_overview AS
SELECT a.appointment_id, a.booking_code, a.customer_id, a.requested_start_at,
       COUNT(i.appointment_item_id) AS item_count,
       CASE
           WHEN COUNT(i.appointment_item_id) = 0 THEN 'empty'
           WHEN bool_and(i.state = 'cancelled') THEN 'cancelled'
           WHEN bool_and(i.state IN ('cancelled','no_show')) THEN 'no_show'
           WHEN bool_and(i.state IN ('completed','cancelled','no_show')) THEN 'completed'
           WHEN bool_or(i.state IN ('in_progress','completed')) THEN 'in_service'
           WHEN bool_or(i.state = 'requested') THEN 'requested'
           ELSE 'confirmed'
       END AS overall_state
FROM appointment a
LEFT JOIN appointment_item i USING (appointment_id)
GROUP BY a.appointment_id;

COMMIT;
